test("validates group graph and routing-policy structure", () => {
  const valid = [
    "[General]",
    "x = y",
    "",
    "[Proxy Group]",
    "A = select,DIRECT",
    "B = select,A",
    "",
    "[Rule]",
    "RULE-SET,https://example.invalid/list,B",
    "AND,((PROTOCOL,UDP),(RULE-SET,https://example.invalid/game)),A",
    "GEOIP,CN,DIRECT",
    "FINAL,B",
    "",
  ].join("\n");
  assert.deepEqual(validateProfile(valid), { valid: true, errors: [] });

  const duplicate = valid.replace("B = select,A", "A = select,A");
  assert.equal(validateProfile(duplicate).valid, false);
  assert.match(validateProfile(duplicate).errors.join("\n"), /duplicate group/i);

  const duplicateSection = valid.replace("[Rule]", "[Rule]\n# duplicate headers must remain visible to validation\n[Rule]");
  assert.equal(validateProfile(duplicateSection).valid, false);
  assert.match(validateProfile(duplicateSection).errors.join("\n"), /duplicate required section/i);

  const missing = valid.replace("B = select,A", "B = select,Missing");
  assert.equal(validateProfile(missing).valid, false);
  assert.match(validateProfile(missing).errors.join("\n"), /missing group/i);

  const cyclic = valid.replace("A = select,DIRECT\nB = select,A", "A = select,B\nB = select,A");
  assert.equal(validateProfile(cyclic).valid, false);
  assert.match(validateProfile(cyclic).errors.join("\n"), /cycle/i);

  const geoipAfterFinal = valid.replace("GEOIP,CN,DIRECT\nFINAL,B", "FINAL,B\nGEOIP,CN,DIRECT");
  assert.equal(validateProfile(geoipAfterFinal).valid, false);
  assert.match(validateProfile(geoipAfterFinal).errors.join("\n"), /GEOIP.*FINAL/i);

  const escapedComma = valid.replace("A = select,DIRECT", "node\\,with\\,comma = random,DIRECT\nA = select,node\\,with\\,comma,Nodes,use=true");
  assert.deepEqual(validateProfile(escapedComma), { valid: true, errors: [] });

  const random = valid.replace("A = select,DIRECT", "A = random,DIRECT");
  assert.deepEqual(validateProfile(random), { valid: true, errors: [] });

  const nonEmojiReference = valid.replace("A = select,DIRECT", "source = random,DIRECT\nA = select,source");
  assert.deepEqual(validateProfile(nonEmojiReference), { valid: true, errors: [] });

  const missingSubscriptionItem = valid.replace("A = select,DIRECT", "A = select,Missing,Nodes,use=true");
  assert.equal(validateProfile(missingSubscriptionItem).valid, false);
  assert.match(validateProfile(missingSubscriptionItem).errors.join("\n"), /missing group/i);

  const danglingNormalizedNode = valid.replace("A = select,DIRECT", "A = select,🇯🇵 [机场] definitely-not-in-subscription");
  assert.equal(validateProfile(danglingNormalizedNode).valid, false);
  assert.match(validateProfile(danglingNormalizedNode).errors.join("\n"), /missing group/i);

  const escapedAndPolicy = valid
    .replace("A = select,DIRECT", "A\\,B = select,DIRECT")
    .replace("B = select,A", "C = select,A\\,B")
    .replace("RULE-SET,https://example.invalid/list,B", "RULE-SET,https://example.invalid/list,C")
    .replace(")),A", ")),A\\,B")
    .replace("FINAL,B", "FINAL,C");
  assert.deepEqual(validateProfile(escapedAndPolicy), { valid: true, errors: [] });

  const missingEscapedAndPolicy = escapedAndPolicy.replace("A\\,B\nGEOIP", "Missing\\,C\nGEOIP");
  assert.equal(validateProfile(missingEscapedAndPolicy).valid, false);
  assert.match(validateProfile(missingEscapedAndPolicy).errors.join("\n"), /AND.*missing group/i);

  const missingAndPolicy = valid.replace(/,A\nGEOIP/, "\nGEOIP");
  assert.equal(validateProfile(missingAndPolicy).valid, false);
  assert.match(validateProfile(missingAndPolicy).errors.join("\n"), /AND.*policy/i);
  assert.deepEqual(validateProfile(null), { valid: false, errors: ["Profile must be a string"] });
});

test("rejects malformed sections, group declarations, and all rule policy forms", () => {
  const supportedRules = [
    "DOMAIN,example.invalid,A",
    "DOMAIN-SUFFIX,example.invalid,A",
    "DOMAIN-KEYWORD,example,A",
    "DOMAIN-WILDCARD,a?.example.invalid,A",
    "IP-CIDR,192.0.2.0/24,A,no-resolve",
    "IP-CIDR6,2001:db8::/32,A,no-resolve",
    "SRC-IP-CIDR,198.51.100.0/24,A,no-resolve",
    "DST-PORT,443-8443,A",
    "DEST-PORT,443,A",
    "USER-AGENT,Example,A",
    "PROCESS-NAME,Example,A",
    "URL-REGEX,^https://example\\.invalid,A",
    "IP-ASN,13335,A",
    "GEOIP,US,A",
    "RULE-SET,https://example.invalid/list,A,update-interval=86400",
    "DOMAIN-SET,https://example.invalid/domains,A,update-interval=86400",
    "OR,((PROTOCOL,TCP),(PROTOCOL,UDP)),A",
    "NOT,(PROTOCOL,UDP),A",
    "AND,((PROTOCOL,UDP),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://example.invalid/nested.list),(DST-PORT,443)),A",
    "AND,((RULE-SET,http://192.0.2.10:8080/list),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://[2001:db8::1]:8443/path),(DST-PORT,443)),A",
  ];
  assert.deepEqual(validateProfile(structuralProfile({ rules: supportedRules })), { valid: true, errors: [] });

  const missingGenericPolicy = structuralProfile({ rules: ["DOMAIN-SUFFIX,example.invalid,Missing"] });
  assert.equal(validateProfile(missingGenericPolicy).valid, false);
  assert.match(validateProfile(missingGenericPolicy).errors.join("\n"), /DOMAIN-SUFFIX.*missing group/i);

  for (const rule of [
    "DOMAIN-SUFFIX,example.invalid",
    "IP-CIDR,not-a-cidr,A",
    "DOMAIN-SUFFIX,..bad..,A",
    "IP-ASN,ASbad,A",
    "DOMAIN,*.example.com,A",
    "DOMAIN-SUFFIX,a?.example.com,A",
    "DOMAIN-WILDCARD,..bad..,A",
    "SRC-IP-CIDR,not-a-cidr,A,no-resolve",
    "DST-PORT,8443-443,A",
    "AND,((PROTOCOL,UDP),(DST-PORT,8443-443)),A",
    "AND,((PROTOCOL,BOGUS),(DST-PORT,443)),A",
    "AND,((UNKNOWN,value),(DST-PORT,443)),A",
    "AND,((RULE-SET,not-a-url),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://:),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://example.com:bad/x),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://[::1/x),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://..),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://-bad.example/x),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://bad-.example/x),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://2001:db8::1/x),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://example.com:0/x),(DST-PORT,443)),A",
    "AND,((RULE-SET,https://example.com:65536/x),(DST-PORT,443)),A",
    "AND,((PROTOCOL,UDP,EXTRA),(DST-PORT,443)),A",
    "UNKNOWN,example.invalid,A",
    "AND,((PROTOCOL,UDP),(RULE-SET,https://example.invalid/game),A",
    "NOT,((PROTOCOL,UDP),(RULE-SET,https://example.invalid/game)),A",
  ]) {
    assert.equal(validateProfile(structuralProfile({ rules: [rule] })).valid, false, rule);
  }

  for (const group of ["A = select", "A = select,use=true"]) {
    assert.equal(validateProfile(structuralProfile({ groups: [group] })).valid, false, group);
    assert.match(validateProfile(structuralProfile({ groups: [group] })).errors.join("\n"), /selectable item|subscription source/i);
  }

  const unescapedGroupName = structuralProfile({ groups: ["A,B = select,DIRECT"] });
  assert.equal(validateProfile(unescapedGroupName).valid, false);
  assert.match(validateProfile(unescapedGroupName).errors.join("\n"), /invalid proxy group/i);
  assert.deepEqual(validateProfile(structuralProfile({
    groups: ["A = select,DIRECT", "A\\,B = select,DIRECT"],
    rules: ["DOMAIN,example.invalid,A\\,B"],
  })), { valid: true, errors: [] });

  const unknownSection = structuralProfile({ extraSections: ["[Extra]"] });
  assert.equal(validateProfile(unknownSection).valid, false);
  assert.match(validateProfile(unknownSection).errors.join("\n"), /unrecognized section/i);

  const duplicateUnknown = structuralProfile({ extraSections: ["[Extra]", "[Extra]"] });
  assert.equal(validateProfile(duplicateUnknown).valid, false);
  assert.match(validateProfile(duplicateUnknown).errors.join("\n"), /duplicate section/i);
});
