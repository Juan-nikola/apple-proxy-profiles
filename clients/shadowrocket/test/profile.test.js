const baseOptions = Object.freeze({
  output: "config",
  type: "collection",
  name: "shadowrocket-sources",
  subscriptionName: "Shadowrocket-Nodes",
  platform: "macos",
  dnsMode: "stable",
  chinaDns: "alidns",
  globalDns: "cloudflare",
  blockMode: "balanced",
  quicMode: "allow",
  ipv6Mode: "auto",
  autoGroupMode: "auto",
  clientChain: "off",
});

function inventory(count) {
  const continents = ["asiaPacific", "europe", "americas", "other"];
  const flags = ["🇯🇵", "🇩🇪", "🇺🇸", "🌐"];
  return Array.from({ length: count }, (_, index) => ({
    // Credentials and transport fields must not be rendered in a Profile.
    name: `${flags[index % flags.length]} node-${index}`,
    password: `TEST_ONLY_NOT_FOR_PROFILE_${index}`,
    _profile: {
      continent: continents[index % continents.length],
      flag: flags[index % flags.length],
      sourceKind: ["airport", "selfHosted", "realm"][index % 3],
      udp: index % 2 === 0,
      p2p: index % 3 === 0,
      entry: index === 0,
      chained: false,
    },
  }));
}

function structuralProfile({ groups = ["A = select,DIRECT"], rules = [], extraSections = [] } = {}) {
  return [
    "[General]",
    "x = y",
    "",
    "[Proxy Group]",
    ...groups,
    "",
    "[Rule]",
    ...rules,
    "GEOIP,CN,DIRECT",
    "FINAL,A",
    ...extraSections,
    "",
  ].join("\n");
}

test("renders a complete, valid macOS profile without node credentials", () => {
  const profile = renderProfile(baseOptions, inventory(25));

  assert.match(profile, /^# Generated by shadowrocket-profile\. Do not paste credentials into this file\.\n# platform=macos; node-count=25; node-refresh=21600; rule-refresh=86400\n/m);
  assert.ok(profile.includes("[General]"));
  assert.ok(profile.includes("[Proxy Group]"));
  assert.ok(profile.includes("[Rule]"));
  assert.equal(profile.includes("not-for-profile"), false);
  assert.equal(profile.endsWith("\n"), true);
  assert.equal(profile.includes("\n\n\n"), false);
  assert.deepEqual(validateProfile(profile), { valid: true, errors: [] });
});

test("uses policy.final as the default of the switchable leak group", () => {
  const nodes = inventory(25);
  const policy = parsePrivatePolicy(JSON.stringify({ schemaVersion: 2, targets: { final: "DIRECT" } }));
  const resolution = resolveUnifiedPolicy({ policy, client: "shadowrocket", allNodes: nodes, eligibleNodes: nodes });
  const profile = renderProfile(baseOptions, nodes, { policyResolution: resolution });

  assert.match(profile, /^漏网之鱼 = select,🚀 节点选择,DIRECT,REJECT,.*policy-select-name=DIRECT/mu);
  assert.match(profile, /^FINAL,漏网之鱼$/mu);
});

test("renders the current lightweight rules by default and permits GEOIP to resolve", () => {
  const profile = renderProfile(baseOptions, inventory(25));
  const rules = profile.slice(profile.indexOf("[Rule]")).split("\n").filter(Boolean);

  assert.match(profile, /current\/shadowrocket\/rules\/DomesticCore\.list/u);
  assert.doesNotMatch(profile, /\/(?:Advertising|Advertising_Domain|ChinaMax_Domain|ChinaMax|Game)\.list/u);
  assert.match(profile, /^RULE-SET,.*\/OverseasGame\.list,🌍 海外游戏,/mu);
  assert.equal(rules.at(-2), "GEOIP,CN,DIRECT");
  assert.equal(rules.at(-1), "FINAL,漏网之鱼");
});

